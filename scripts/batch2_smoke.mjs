// Run with an existing Playwright module; no project dependency installation.
import { spawn } from 'node:child_process'
import { setTimeout as pause } from 'node:timers/promises'
import { pathToFileURL } from 'node:url'
import assert from 'node:assert/strict'

const { chromium } = await import(process.argv[2] ? pathToFileURL(process.argv[2]).href : 'playwright')
const server = spawn('.venv/bin/python', ['scripts/batch2_smoke_server.py'], { env: { ...process.env, PYTHONPATH: 'src' }, stdio: ['ignore', 'inherit', 'inherit'] })
let browser
try {
  for (let i = 0; i < 60; i++) {
    if (server.exitCode !== null) throw new Error('Fixture server exited early')
    try { if ((await fetch('http://127.0.0.1:8011/api/health')).ok) break } catch { /* Wait for local fixture only. */ }
    if (i === 59) throw new Error('Fixture did not start')
    await pause(200)
  }
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox'] })
  const page = await browser.newPage({ viewport: { width: 1360, height: 940 }, reducedMotion: 'reduce' })
  page.setDefaultTimeout(10000)
  const errors = []
  const remoteWrites = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/\/api\/(sync|analyze)\//.test(request.url())) remoteWrites.push(request.url()) })
  await page.route('https://fonts.googleapis.com/**', route => route.abort())
  await page.goto('http://127.0.0.1:8011')
  async function navigate(name) {
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
    await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name, exact: true }).click()
    await page.getByRole('heading', { name, exact: true, level: 1 }).waitFor()
  }
  async function readyMailbox(name) {
    await page.getByRole('region', { name: `${name} mailbox` }).getByRole('button', { name: /^Open / }).first().waitFor()
  }
  await navigate('Orders'); await readyMailbox('Orders')
  assert.equal(await page.locator('.v5-mail-row').count(), 5)
  assert.equal(await page.locator('.v5-category-mailbox').getByText('possible_transaction', { exact: true }).count(), 0)
  assert.equal(await page.locator('.v5-mail-row').getByText('Big sale - shop now').count(), 0)
  await page.screenshot({ path: '/tmp/postmark-batch2-orders-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Mark Done: Your order has shipped', exact: true }).click()
  await page.getByText('Message marked Done.', { exact: true }).waitFor()
  await page.getByRole('button', { name: /^Done\s*1$/, exact: true }).click()
  await page.getByRole('button', { name: /^Open Your order has shipped/ }).waitFor()
  await page.reload()
  await navigate('Orders')
  await page.getByRole('button', { name: /^Done\s*1$/, exact: true }).click()
  await page.getByRole('button', { name: /^Open Your order has shipped/ }).click()
  await page.getByRole('dialog', { name: 'Your order has shipped' }).waitFor()
  await page.getByText('Full message fixture for personal.', { exact: false }).waitFor()
  await page.getByText('Change category', { exact: true }).click()
  await page.getByLabel('Find a category').fill('Security')
  await page.getByRole('group', { name: 'Choose category' }).getByRole('button', { name: 'Security', exact: true }).click()
  await page.getByRole('button', { name: 'Move message', exact: true }).click()
  await page.getByText('Moved to Security.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  await navigate('Security')
  await page.getByRole('button', { name: /^Done\s*1$/, exact: true }).click()
  await page.getByRole('button', { name: /^Open Your order has shipped/ }).waitFor()
  await page.getByRole('button', { name: 'Return to New: Your order has shipped', exact: true }).click()
  await page.getByRole('button', { name: /^New\s*3$/, exact: true }).click()
  await readyMailbox('Security')
  await page.getByLabel('Search Security').fill('password')
  await page.getByRole('button', { name: /^Open Your password was updated/ }).waitFor()
  assert.equal(await page.locator('.v5-mail-row').count(), 1)
  await page.getByLabel('Clear search').click()
  await readyMailbox('Security')
  await page.getByLabel('Sort messages').selectOption('oldest')
  await page.waitForFunction(() => document.querySelector('.v5-mail-row .v5-message-data > span')?.textContent === 'Your password was updated')
  await page.getByLabel('Choose email account').selectOption('university')
  await page.waitForURL('**account=university')
  await readyMailbox('Security')
  assert.equal(await page.locator('.v5-mail-row').count(), 2)
  await page.getByRole('button', { name: /^Open Your password was updated/ }).click()
  await page.getByText('Full message fixture for university.', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'Close details' }).click()
  await navigate('Categories')
  await page.locator('.v5-category-tile').first().waitFor()
  await page.screenshot({ path: '/tmp/postmark-batch2-settings-desktop.png', fullPage: true })
  const travel = page.locator('.v5-suggestion').filter({ hasText: 'Travel' })
  await travel.getByRole('button', { name: 'Approve', exact: true }).click()
  await page.getByText('Travel is ready. Find it in navigation.', { exact: true }).waitFor()
  await navigate('Travel')
  await page.getByText('You’re all caught up', { exact: true }).waitFor()
  await navigate('Categories')
  const scholarship = page.locator('.v5-suggestion').filter({ hasText: 'Scholarships' })
  await scholarship.getByRole('button', { name: 'Dismiss', exact: true }).click()
  await page.getByText('Scholarships suggestion dismissed.', { exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await navigate('Orders'); await readyMailbox('Orders')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await page.screenshot({ path: '/tmp/postmark-batch2-orders-mobile.png', fullPage: true })
  await page.getByRole('region', { name: 'Orders mailbox' }).getByRole('button', { name: /^Open / }).first().click()
  await page.getByRole('button', { name: 'Close details', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Close details', await page.evaluate(() => document.activeElement?.outerHTML))
  await page.keyboard.press('Shift+Tab')
  assert.equal(await page.evaluate(() => Boolean(document.querySelector('[role=dialog]')?.contains(document.activeElement))), true)
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Close details', await page.evaluate(() => document.activeElement?.outerHTML))
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  await page.getByRole('button', { name: 'Quick search', exact: true }).click()
  await page.getByLabel('Search all stored emails').fill('Your order has shipped')
  await page.locator('.v5-search-results button').filter({ hasText: 'personal' }).first().click()
  await page.getByText('Full message fixture for personal.', { exact: false }).waitFor()
  await page.getByText('Gmail actions', { exact: false }).first().click()
  await page.getByRole('button', { name: 'Move to Trash…', exact: true }).click()
  await page.getByText('Read-only account', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Confirm Gmail Trash', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: 'Review subscription options', exact: true }).waitFor()
  assert.deepEqual(errors, [])
  assert.deepEqual(remoteWrites, [])
  console.log('PASS: persisted Done/reload, category moves preserving state, Return to New, account isolation, full message navigation, search, approve/dismiss/navigation, mobile overflow, dialog focus/Escape; no live Gmail or AI requests.')
} finally {
  await browser?.close()
  server.kill('SIGTERM')
}
